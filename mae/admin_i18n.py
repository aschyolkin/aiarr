# Short words that are only safe as whole cells; applied last.
ANCHORED = [
    (r"^нет$", "none"),
    (r"^пусто$", "empty"),
    (r"^проверенная карточка", "verified card"),
    (r"^карточка( \(|$)", "card$1"),
    (r"(^|[ ,])ошибка($|[:,.])", "$1error$2"),
    (r"(^|, )пусто(: |$)", "$1empty$2"),
    (r"(\d) мс$", "$1 ms"),
    (r"(\d) с$", "$1 s"),
]


def rules():
    literal = [(re.escape(ru), en) for ru, en in sorted(LITERALS.items(), key=lambda kv: -len(kv[0]))]
    return [list(item) for item in COMPOSITE + literal + ANCHORED]


def rules_json():
    return json.dumps(rules(), ensure_ascii=False, separators=(",", ":"))


def translate(text):
    """Python twin of the browser's ``t()``; used by the tests."""
    text = re.sub(r"\s+", " ", text)
    for pattern, repl in rules():
        text = re.sub(pattern, re.sub(r"\$(\d)", r"\\g<\1>", repl), text)
    return text
